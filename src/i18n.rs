//! Internationalization (i18n) module.
//!
//! Provides multi-language support across 12 languages:
//! - English (EN)
//! - Spanish (ES)
//! - French (FR)
//! - German (DE)
//! - Italian (IT)
//! - Portuguese (PT)
//! - Dutch (NL)
//! - Polish (PL)
//! - Turkish (TR)
//! - Tamil (TA)
//! - Japanese (JA)
//! - Chinese (ZH)

use serde::{Deserialize, Serialize};

/// Supported languages enumeration.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum Language {
    En,
    Es,
    Fr,
    De,
    It,
    Pt,
    Nl,
    Pl,
    Tr,
    Ta,
    Ja,
    Zh,
}

impl Default for Language {
    fn default() -> Self {
        Language::En
    }
}

impl Language {
    /// Returns a list of all 12 supported languages in canonical order.
    pub const fn all() -> &'static [Language] {
        &[
            Language::En,
            Language::Es,
            Language::Fr,
            Language::De,
            Language::It,
            Language::Pt,
            Language::Nl,
            Language::Pl,
            Language::Tr,
            Language::Ta,
            Language::Ja,
            Language::Zh,
        ]
    }

    /// Two-letter ISO 639-1 language code.
    pub const fn code(&self) -> &'static str {
        match self {
            Language::En => "en",
            Language::Es => "es",
            Language::Fr => "fr",
            Language::De => "de",
            Language::It => "it",
            Language::Pt => "pt",
            Language::Nl => "nl",
            Language::Pl => "pl",
            Language::Tr => "tr",
            Language::Ta => "ta",
            Language::Ja => "ja",
            Language::Zh => "zh",
        }
    }

    /// Autonym / native display name for the language.
    pub const fn name(&self) -> &'static str {
        match self {
            Language::En => "English",
            Language::Es => "Español",
            Language::Fr => "Français",
            Language::De => "Deutsch",
            Language::It => "Italiano",
            Language::Pt => "Português",
            Language::Nl => "Nederlands",
            Language::Pl => "Polski",
            Language::Tr => "Türkçe",
            Language::Ta => "தமிழ்",
            Language::Ja => "日本語",
            Language::Zh => "中文",
        }
    }

    /// Short label for UI display (e.g. "Português", "English").
    pub fn display_label(&self) -> String {
        self.name().to_string()
    }

    /// Parses a language code or prefix (e.g. "en", "es-ES", "pt_BR").
    pub fn from_code(code: &str) -> Option<Language> {
        let clean = code.trim().to_lowercase();
        let primary = clean.split(&['-', '_'][..]).next().unwrap_or(&clean);
        match primary {
            "en" => Some(Language::En),
            "es" => Some(Language::Es),
            "fr" => Some(Language::Fr),
            "de" => Some(Language::De),
            "it" => Some(Language::It),
            "pt" => Some(Language::Pt),
            "nl" => Some(Language::Nl),
            "pl" => Some(Language::Pl),
            "tr" => Some(Language::Tr),
            "ta" => Some(Language::Ta),
            "ja" => Some(Language::Ja),
            "zh" => Some(Language::Zh),
            _ => None,
        }
    }

    /// Cycles to the next supported language.
    pub fn next(&self) -> Language {
        let all = Self::all();
        let current_idx = all.iter().position(|l| l == self).unwrap_or(0);
        all[(current_idx + 1) % all.len()]
    }

    /// Attempts to detect system locale from OS APIs or environment variables.
    pub fn detect_system_language() -> Language {
        #[cfg(windows)]
        {
            extern "system" {
                fn GetUserDefaultLocaleName(lpLocaleName: *mut u16, cchLocaleName: i32) -> i32;
            }
            let mut buffer = [0u16; 85];
            let len = unsafe { GetUserDefaultLocaleName(buffer.as_mut_ptr(), buffer.len() as i32) };
            if len > 1 {
                let name = String::from_utf16_lossy(&buffer[..(len as usize - 1)]);
                if let Some(lang) = Self::from_code(&name) {
                    return lang;
                }
            }
        }

        #[cfg(target_os = "macos")]
        {
            if let Ok(output) = std::process::Command::new("defaults")
                .args(["read", "-g", "AppleLocale"])
                .output()
            {
                if output.status.success() {
                    let val = String::from_utf8_lossy(&output.stdout);
                    if let Some(lang) = Self::from_code(&val) {
                        return lang;
                    }
                }
            }
        }

        // Standard POSIX / Linux environment variables (LANG, LC_ALL, LC_MESSAGES)
        for var in &["LC_ALL", "LC_MESSAGES", "LANG"] {
            if let Ok(val) = std::env::var(var) {
                if let Some(lang) = Self::from_code(&val) {
                    return lang;
                }
            }
        }
        Language::En
    }
}

/// Translates a key for the given language, falling back to English if missing.
pub fn t<'a>(lang: Language, key: &'a str) -> &'a str {
    get_dict(lang)
        .and_then(|d| d(key))
        .or_else(|| get_dict(Language::En).and_then(|d| d(key)))
        .unwrap_or(key)
}

/// Translates a key and replaces `{param}` placeholders with given values.
pub fn t_param(lang: Language, key: &str, params: &[(&str, &str)]) -> String {
    let mut text = t(lang, key).to_string();
    for &(k, v) in params {
        let placeholder = format!("{{{}}}", k);
        text = text.replace(&placeholder, v);
    }
    text
}

type DictFn = fn(&str) -> Option<&'static str>;

fn get_dict(lang: Language) -> Option<DictFn> {
    match lang {
        Language::En => Some(dict_en),
        Language::Es => Some(dict_es),
        Language::Fr => Some(dict_fr),
        Language::De => Some(dict_de),
        Language::It => Some(dict_it),
        Language::Pt => Some(dict_pt),
        Language::Nl => Some(dict_nl),
        Language::Pl => Some(dict_pl),
        Language::Tr => Some(dict_tr),
        Language::Ta => Some(dict_ta),
        Language::Ja => Some(dict_ja),
        Language::Zh => Some(dict_zh),
    }
}

